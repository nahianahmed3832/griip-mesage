package com.meldiq.android.data.model

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/** One emoji of the catalogue: its search words, the Emoji version that added it, and its five skin tones if it has them. */
data class EmojiItem(val emoji: String, val name: String, val keywords: String, val version: String, val tones: List<String>? = null) {
    /** This emoji in skin tone [tone] (0: none, 1–5: light to dark); itself when it has no tones. */
    fun inTone(tone: Int): String = tones?.getOrNull(tone - 1) ?: emoji
}

/** A category of the picker ("smileys", "people", …) in Unicode's recommended order. */
data class EmojiGroup(val id: String, val name: String, val items: List<EmojiItem>)

/**
 * The Unicode emoji catalogue (docs/EMOJI.md), generated by tools/emoji/gen_emoji.py into assets/emoji/emoji.json from
 * Unicode's emoji-test.txt and CLDR's English annotations. Parsing and search only: loading and font checks are
 * [com.meldiq.android.data.repo.EmojiData].
 */
object EmojiCatalog {
    const val TONE_COUNT = 5
    /** How many results a search shows at most. */
    const val SEARCH_LIMIT = 120

    fun parse(text: String): List<EmojiGroup> =
        Json.parseToJsonElement(text).jsonObject.getValue("groups").jsonArray.map { g ->
            val o = g.jsonObject
            EmojiGroup(
                id = o.getValue("id").jsonPrimitive.content,
                name = o.getValue("name").jsonPrimitive.content,
                items = o.getValue("items").jsonArray.map { row -> item(row.jsonArray) },
            )
        }

    private fun item(row: JsonArray) = EmojiItem(
        emoji = row[0].jsonPrimitive.content,
        name = row[1].jsonPrimitive.content,
        keywords = row[2].jsonPrimitive.content,
        version = row[3].jsonPrimitive.content,
        tones = row.getOrNull(4)?.jsonArray?.map { it.jsonPrimitive.content }?.takeIf { it.size == TONE_COUNT },
    )

    /**
     * Emoji whose name or search words start with every word of [query] ("thumb up" finds 👍), best first: the name
     * starting with the query, then a word of the name, then a search word. Blank: nothing.
     */
    fun search(groups: List<EmojiGroup>, query: String, limit: Int = SEARCH_LIMIT): List<EmojiItem> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()
        val terms = q.split(WHITESPACE).filter { it.isNotEmpty() }
        return groups.asSequence().flatMap { it.items.asSequence() }
            .mapNotNull { item -> rank(item, q, terms)?.let { item to it } }
            .sortedBy { it.second }
            .take(limit)
            .map { it.first }
            .toList()
    }

    /** Lower is better; null: no match. */
    private fun rank(item: EmojiItem, query: String, terms: List<String>): Int? {
        val nameWords = item.name.split(WORD_BREAK)
        val keyWords = item.keywords.split(' ')
        if (!terms.all { t -> nameWords.any { it.startsWith(t) } || keyWords.any { it.startsWith(t) } }) return null
        return when {
            item.name == query -> 0
            item.name.startsWith(query) -> 1
            terms.all { t -> nameWords.any { it.startsWith(t) } } -> 2
            else -> 3
        }
    }

    private val WHITESPACE = Regex("\\s+")
    private val WORD_BREAK = Regex("[\\s:,]+")
}

/** What a reaction may be (docs/EMOJI.md): one emoji, not text. Checked on send and on every reaction received. */
object EmojiRules {
    /** The same ceiling as Meldiq Web's payload schema; the longest standard emoji (families with tones) is about 35. */
    const val REACTION_MAX = 64

    /** Emoji presentation selector: makes a symbol that is also a letter (ℹ, Ⓜ) an emoji. */
    private const val EMOJI_PRESENTATION = 0xFE0F

    fun isReaction(value: String?): Boolean {
        if (value.isNullOrEmpty() || value.length > REACTION_MAX) return false
        var i = 0
        while (i < value.length) {
            val cp = value.codePointAt(i)
            val next = i + Character.charCount(cp)
            if (Character.isWhitespace(cp) || Character.isISOControl(cp)) return false
            if (Character.isLetter(cp) && (next >= value.length || value.codePointAt(next) != EMOJI_PRESENTATION)) return false
            i = next
        }
        return true
    }
}
